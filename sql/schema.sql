-- =============================================================================
-- Court Case Management System - Database Schema Script
-- Oracle Database 21c Syntax
-- =============================================================================

-- Drop all existing tables safely in reverse order of dependencies
BEGIN
   FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'AUDIT_LOG', 'CITATION', 'CASE_STATUTE', 'CASE_PARTY', 'REPRESENTS',
      'STATUTE', 'HEARING', 'PARTY', 'LAWYER', 'COURT_CASE', 'JUDGE', 'COURT'
   )) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE "' || t.table_name || '" CASCADE CONSTRAINTS PURGE';
   END LOOP;
END;
/

-- 1. COURT TABLE
-- Represents judicial courts across various hierarchy levels
CREATE TABLE COURT (
    Court_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Court_Name VARCHAR2(100) NOT NULL,
    Court_Level VARCHAR2(20) NOT NULL CHECK (Court_Level IN ('District', 'High', 'Supreme')),
    Location VARCHAR2(100) NOT NULL
);

-- 2. JUDGE TABLE
-- Stores judge details assigned to specific courts
CREATE TABLE JUDGE (
    Judge_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Judge_Name VARCHAR2(100) NOT NULL,
    Designation VARCHAR2(100),
    Court_ID NUMBER REFERENCES COURT(Court_ID) ON DELETE SET NULL
);

-- 3. COURT_CASE TABLE
-- Core table storing legal case details (named COURT_CASE as CASE is an Oracle reserved word)
CREATE TABLE COURT_CASE (
    Case_No VARCHAR2(20) PRIMARY KEY,
    Case_Title VARCHAR2(150) NOT NULL,
    Filing_Date DATE NOT NULL,
    Case_Type VARCHAR2(50),
    Status VARCHAR2(20) NOT NULL CHECK (Status IN ('Open', 'Closed', 'Under Appeal')),
    Court_ID NUMBER REFERENCES COURT(Court_ID) ON DELETE SET NULL
);

-- 4. LAWYER TABLE
-- Information on advocates practicing in courts
CREATE TABLE LAWYER (
    Lawyer_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Lawyer_Name VARCHAR2(100) NOT NULL,
    Bar_Reg_No VARCHAR2(50) UNIQUE NOT NULL,
    Specialization VARCHAR2(100)
);

-- 5. PARTY TABLE
-- Litigants (Petitioners, Respondents, Defendants, Plaintiffs)
CREATE TABLE PARTY (
    Party_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Party_Name VARCHAR2(100) NOT NULL,
    Contact_No VARCHAR2(20)
);

-- 6. HEARING TABLE
-- Scheduled case hearings before judges
CREATE TABLE HEARING (
    Hearing_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Case_No VARCHAR2(20) NOT NULL REFERENCES COURT_CASE(Case_No) ON DELETE CASCADE,
    Judge_ID NUMBER REFERENCES JUDGE(Judge_ID) ON DELETE SET NULL,
    Hearing_Date DATE NOT NULL,
    Remarks VARCHAR2(255)
);

-- 7. STATUTE TABLE
-- Legal acts and sections referenced in cases
CREATE TABLE STATUTE (
    Statute_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Act_Name VARCHAR2(100) NOT NULL,
    Section_No VARCHAR2(50) NOT NULL,
    Description VARCHAR2(255)
);

-- 8. REPRESENTS TABLE
-- Ternary junction table linking Lawyers, Parties, and Cases
CREATE TABLE REPRESENTS (
    Lawyer_ID NUMBER REFERENCES LAWYER(Lawyer_ID) ON DELETE CASCADE,
    Party_ID NUMBER REFERENCES PARTY(Party_ID) ON DELETE CASCADE,
    Case_No VARCHAR2(20) REFERENCES COURT_CASE(Case_No) ON DELETE CASCADE,
    Role VARCHAR2(50),
    PRIMARY KEY (Lawyer_ID, Party_ID, Case_No)
);

-- 9. CASE_PARTY TABLE
-- Junction table associating cases with involved parties
CREATE TABLE CASE_PARTY (
    Case_No VARCHAR2(20) REFERENCES COURT_CASE(Case_No) ON DELETE CASCADE,
    Party_ID NUMBER REFERENCES PARTY(Party_ID) ON DELETE CASCADE,
    PRIMARY KEY (Case_No, Party_ID)
);

-- 10. CASE_STATUTE TABLE
-- Junction table linking cases with applicable statutes/sections
CREATE TABLE CASE_STATUTE (
    Case_No VARCHAR2(20) REFERENCES COURT_CASE(Case_No) ON DELETE CASCADE,
    Statute_ID NUMBER REFERENCES STATUTE(Statute_ID) ON DELETE CASCADE,
    PRIMARY KEY (Case_No, Statute_ID)
);

-- 11. CITATION TABLE
-- Legal precedents (which case cited which prior case)
CREATE TABLE CITATION (
    Citing_Case_No VARCHAR2(20) REFERENCES COURT_CASE(Case_No) ON DELETE CASCADE,
    Cited_Case_No VARCHAR2(20) REFERENCES COURT_CASE(Case_No) ON DELETE CASCADE,
    Citation_Date DATE DEFAULT SYSDATE,
    CHECK (Citing_Case_No <> Cited_Case_No),
    PRIMARY KEY (Citing_Case_No, Cited_Case_No)
);

-- 12. AUDIT_LOG TABLE
-- Logs status changes of cases via trigger
CREATE TABLE AUDIT_LOG (
    Log_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Case_No VARCHAR2(20),
    Old_Status VARCHAR2(20),
    New_Status VARCHAR2(20),
    Changed_On DATE DEFAULT SYSDATE
);

COMMIT;
